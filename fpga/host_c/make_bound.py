#!/usr/bin/env python3
"""make_bound.py - bound_main.c (bound-miner) da rigor_main.c (rigor-miner 1.0, a sua volta da csd-miner 1.4.5).

  python3 make_bound.py rigor_main.c bound_main.c

Cosa cambia: PoW BoundHash (bound_pow.c, stesse funzioni di rigor_pow.c con prefisso bp_), merkle root
di BOUND (hash con etichetta invece di sha256d), velocita' in H/s (un core fa ~1 kH/s: nominale =
core x MHz x 10^6 / 90660), lavoro che non si esaurisce (si rinnova ogni --job-s, default 30 s), ordine
dei byte "raw" fisso (lo stratum e' quello di pc_bridge/bound_bridge.py), tetto del clock = build + 15 MHz,
--max-cands 4 (ogni candidato costa un BoundHash sull'ARM), opzione --lines per le prove su regtest,
dev fee 3 % sullo stesso ponte dell'utente con l'indirizzo dello sviluppatore (bound-miner 1.1).
Tutto il resto (catena, ventole, clock DRP, web, API, loader, profili, fee) resta com'e'.
"""
import sys, re
src, dst = sys.argv[1], sys.argv[2]
s = open(src).read()
n_rep = 0
def rep(a, b, count=1):
    global s, n_rep
    assert s.count(a) == count, (a[:70], s.count(a))
    s = s.replace(a, b); n_rep += 1

# ---- testata
i = s.index("#define _GNU_SOURCE")
s = '''/* bound-miner - host program for the BOUND (BoundHash) bitstream on BlackMiner hash boards.
 * Generated by make_bound.py from rigor-miner 1.0 (csd-miner 1.4.5).
 *
 * PoW: BoundHash(header_80), valid if Uint256_LE(hash) <= target (512 KiB scratchpad per hash).
 * The FPGA gets the SHA-256 state after the first 64 header bytes plus header bytes 64..75;
 * every core tries base + {core, position, counter} and reports the nonces whose hash >> 192
 * is <= target64; the host recomputes the full BoundHash of every result before submitting it.
 *
 *   bound-miner --bench 60
 *   bound-miner --pool stratum+tcp://IP_DEL_PC:7340 --user B....ultra1     (pc_bridge/bound_bridge.py)
 *   bound-miner ... --freq 95             (hash clock of the bitstream, MMCM DRP)
 *   bound-miner --default-config /config/cgminer.conf      (web mode: started by cgminer.sh)
 *
 * Work distribution: every FPGA gets its own extranonce2, i.e. its own header. A job never runs
 * out (about 1 kH/s per core against 2^25 counters): a fresh header goes out every --job-s
 * (default 30 s) and at every new pool job.
 *
 * Board slots (vendor driver): slot i -> /dev/ttyO{1,2,4,5}, presence GPIO
 * {22,27,47,115} (1 = board present).  Override with --port.
 */
''' + s[i:]

# ---- PoW e merkle
rep('#include "rigor_pow.h"', '#include "bound_pow.h"')
s, k = re.subn(r'\brp_', 'bp_', s); assert k >= 10
s = s.replace('RP_STATE_BYTES', 'BP_STATE_BYTES')
rep('    cp_merkle(cb, cbn, (const uint8_t (*)[32])j->branch, j->nbranch, mr);',
    '    bp_merkle(cb, cbn, (const uint8_t (*)[32])j->branch, j->nbranch, mr);')

# ---- velocita' nominale e durata del lavoro
rep('static double fpga_nominal(const fpga_t *f) { return f->present ? (double)f->cores * f->mhz * 1e6 : 0; }',
    'static double fpga_nominal(const fpga_t *f) { return f->present ? (double)f->cores * f->mhz * 1e6 / BP_CLOCKS_PER_HASH : 0; }')
rep('    return f->mhz > 0 ? 0.8 * 536870912.0 / (f->mhz * 1e6) : 2;', '    (void)f; return 30;')
rep('double job_s;               /* new job for an FPGA after this many seconds (0 = 80 % of its range) */',
    'double job_s;               /* new job for an FPGA after this many seconds (0 = 30 s) */')

# ---- ordine dei byte: raw (ponte)
rep('static int cur_order = 1;', 'static int cur_order = 2;')
rep('cur_order = opt.byteorder ? opt.byteorder : (o ? o : 1);', 'cur_order = opt.byteorder ? opt.byteorder : (o ? o : 2);')
rep('if (opt.byteorder == 0 && pend[i].order == cur_order && ++order_rejects >= 8 && order_rejects > 4 * order_accepts) {',
    'if (0 && opt.byteorder == 0 && pend[i].order == cur_order && ++order_rejects >= 8 && order_rejects > 4 * order_accepts) {')

# ---- unita': H/s e kH/s
rep('" %d:%.0fC %s %.0fMH/s", k, f->temp, st, f->rate / 1e6);', '" %d:%.0fC %s %.0fH/s", k, f->temp, st, f->rate);')
rep('logm("board%d(%s) %.0f MH/s |%s", c->idx, c->port, r / 1e6, parts);', 'logm("board%d(%s) %.0f H/s |%s", c->idx, c->port, r, parts);')
rep('logm("total %.2f GH/s | diff %.0f | shares', 'logm("total %.2f kH/s | diff %.3g | shares')
rep('             tot / 1e9, share_diff, accepted,', '             tot / 1e3, share_diff, accepted,')
rep('logm("total %.2f GH/s | fan %d%% %d/%d rpm", tot / 1e9, fan_pct', 'logm("total %.2f kH/s | fan %d%% %d/%d rpm", tot / 1e3, fan_pct')
rep('%d FPGA, %d sha256d cores, %s%s MHz (built for %d), bitstream v%d.%d -> nominal %.0f MH/s",',
    '%d FPGA, %d BoundHash cores, %s%s MHz (built for %d), bitstream v%d.%d -> nominal %.0f H/s",')
rep('f0->built_mhz, f0->vmaj, f0->vmin, chain_nominal(c) / 1e6);', 'f0->built_mhz, f0->vmaj, f0->vmin, chain_nominal(c));')
rep('-> %.0f MH/s from results, %.0f from counters (nominal %.0f)",', '-> %.0f H/s from results, %.0f from counters (nominal %.0f)",')
rep('c->idx, good, bad, el, est / 1e6, chain_rate(c) / 1e6, chain_nominal(c) / 1e6);', 'c->idx, good, bad, el, est, chain_rate(c), chain_nominal(c));')
# API cgminer: le chiavi restano (GHS, MHS), con abbastanza decimali per i kH/s
s, k = re.subn(r'kv_n\("GHS (5s|av)", "%\.4f"', r'kv_n("GHS \1", "%.9f"', s); assert k == 4, k
s, k = re.subn(r'kv_n\("MHS (5s|av)", "%\.2f"', r'kv_n("MHS \1", "%.6f"', s); assert k == 2, k
rep('kv_s(k, acn[i] ? "%.4f" : "0", rate[i] / 1e9);', 'kv_s(k, acn[i] ? "%.9f" : "0", rate[i] / 1e9);')

# ---- clock: tetto = build + 15 MHz
rep('double ceil_mhz = opt.freq_max > 0 ? opt.freq_max : (f->built_mhz + 75 > 300 ? f->built_mhz + 75 : 300);',
    'double ceil_mhz = opt.freq_max > 0 ? opt.freq_max : f->built_mhz + 15;')
rep('/* ceiling: --freq-max, else 300 MHz or 75 above the build clock */', '/* ceiling: --freq-max, else 15 MHz above the build clock */')
rep('int freq_max;               /* --freq-max: ceiling for the hash clock (0 = 300 or build + 75) */',
    'int freq_max;               /* --freq-max: ceiling for the hash clock (0 = build + 15) */')

# ---- default e opzione --lines
rep('opt.status_s = 1; opt.max_cands = 50;', 'opt.status_s = 1; opt.max_cands = 4;')
rep('        else if (ARG("--job-s")) opt.job_s = atof(v);',
    '        else if (ARG("--job-s")) opt.job_s = atof(v);\n'
    '        else if (ARG("--lines")) { if (bp_set_lines((unsigned)atoi(v))) { fprintf(stderr, "--lines: a power of two from 2 to 1048576\\n"); return 2; } }')

# ---- dev fee: BOUND non ha pool, quindi la finestra della fee si fa sullo stesso ponte dell'utente, autorizzandosi
#      con l'indirizzo dello sviluppatore (il ponte chiede al nodo un template che paga quell'indirizzo)
rep('#define DEVFEE_PERCENT   2', '#define DEVFEE_PERCENT   3')
rep('#define DEVFEE_ADDRESS   "rg1q_DEV_FEE_ADDRESS_TODO"     /* ORU payout address of the developer */',
    '#define DEVFEE_ADDRESS   "BW1chX39ABzxeVgHqqmTDGL5woHd6GAgj2rqVm4iw4Ty5fG7K1Y7"   /* BOUND address of the developer */')
rep("""/* Dev fee (declared at start-up, in --help and in the LEGGIMI): 2% of the time -
   120 s every 100 minutes - the miner works for the developer's address on the
   same pool. Same mechanism as noid-miner. */""",
    """/* Dev fee (declared at start-up, in --help and in the LEGGIMI): DEVFEE_PERCENT % of the time
   (3 % = 180 s every 100 minutes) the miner logs in to the same bridge with the developer's
   address, so the blocks found in that window pay the developer. Same mechanism as noid-miner. */""")
rep('/* fee window always on the original pool of this coin, whatever pool the user mines on */',
    "/* BOUND has no pool: the fee window runs on the user's own bridge */")
rep('#ifndef DEVFEE_POOL\n#define DEVFEE_POOL      "stratum+tcp://rgr.ariabrain.com:3356"\n#endif\n', '')
rep('            const char *url = devfee_active ? DEVFEE_POOL : opt.pools[cur_pool];', '            const char *url = opt.pools[cur_pool];')
rep("""               DEVFEE_ADDRESS " (worker .devfee), always on the original pool " DEVFEE_POOL "\\n"
               "whatever pool you use (if it does not answer the window is skipped). The benchmark has no fee.\\n",""",
    """               DEVFEE_ADDRESS " (worker .devfee):\\n"
               "in that window the miner logs in to your bridge with that address. The benchmark has no fee.\\n",""")
rep("""            logm("dev fee %d%%: %.0f s every %.0f min on %s, always on the original pool %s", DEVFEE_PERCENT,
                 DEVFEE_CYCLE_S * DEVFEE_PERCENT / 100.0, DEVFEE_CYCLE_S / 60, DEVFEE_ADDRESS, DEVFEE_POOL);""",
    """            logm("dev fee %d%%: %.0f s every %.0f min the miner works for %s (on your own bridge)", DEVFEE_PERCENT,
                 DEVFEE_CYCLE_S * DEVFEE_PERCENT / 100.0, DEVFEE_CYCLE_S / 60, DEVFEE_ADDRESS);""")

# ---- nomi
rep('#define VERSION "1.0"', '#define VERSION "1.1"')
rep('rigor-f2/%s-rgrpow01', 'bound-fpga/%s-boundhash')
# difficolta' suggerita: frazionaria (una share ogni --suggest-s a ~kH/s vuol dire diff << 1)
rep('''\\"mining.suggest_difficulty\\",\\"params\\":[%.0f]}\\n",
                         nom * opt.suggest_s / 4294967296.0 < 1 ? 1 : nom * opt.suggest_s / 4294967296.0);''',
    '''\\"mining.suggest_difficulty\\",\\"params\\":[%.6g]}\\n",
                         nom * opt.suggest_s / 4294967296.0);''')
rep('memcmp(r + 4, "RGR1", 4)', 'memcmp(r + 4, "BND1", 4)')
rep('"fpgaminer_top_rigor.bit"', '"fpgaminer_top_bound.bit"')
for a, b in (('RIGOR (ORU, OpuHash)', 'BOUND (BoundHash)'), ('OpuHash', 'BoundHash'), ('RIGOR', 'BOUND'), ('Rigor', 'Bound'),
             ('rigor', 'bound'), ('rgrpow01', 'boundhash')):
    s = s.replace(a, b)
for a, b in (('--user rg1q...[.rig]   ORU payout address', '--user B....[.rig]     BOUND address        '),
             ('miner for BlackMiner F2 FPGA hash boards', 'miner for BlackMiner FPGA hash boards (F1 Ultra, F2, F1 Plus)'),
             ('logm("pool: difficulty %.3f", share_diff);', 'logm("pool: difficulty %.6g", share_diff);')):
    assert s.count(a) == 1, a
    s = s.replace(a, b)
assert 'RGR' not in s and 'rigor' not in s.lower(), [l for l in s.splitlines() if 'rigor' in l.lower() or 'RGR' in l][:5]
open(dst, 'w').write(s)
print("bound_main.c: %d sostituzioni verificate, %d righe" % (n_rep, s.count('\n')))
